describe("parseLyrics", () => {
  const texts = (lyrics: string, includeMarkup = true) =>
    parseLyrics(lyrics, includeMarkup).map(({ text }) => text);

  test("turns a word or syllable break before a line break into the line break", () => {
    expect(texts("foo_\nbar")).toEqual(["foo\n", "bar"]);
    expect(texts("foo/\nbar")).toEqual(["foo\n", "bar"]);
    expect(texts("foo_\n\nbar")).toEqual(["foo\n\n", "bar"]);
    expect(texts("foo\n_bar")).toEqual(["foo\n", "bar"]);
  });

  test("collapses blank lines to one page break", () => {
    expect(texts("foo\n\n\nbar")).toEqual(["foo\n\n", "bar"]);
    expect(texts("foo\n\n\n\nbar")).toEqual(["foo\n\n", "bar"]);
  });

  test("collapses repeated breaks within a line", () => {
    expect(texts("a__b")).toEqual(["a_", "b"]);
    expect(texts("a//b")).toEqual(["a/", "b"]);
    expect(texts("a/_b")).toEqual(["a_", "b"]);
  });

  test("drops a segment of whitespace but keeps its break", () => {
    expect(texts("foo_ \nbar")).toEqual(["foo\n", "bar"]);
    expect(texts("foo\n \nbar")).toEqual(["foo\n\n", "bar"]);
    expect(texts("foo_ _bar")).toEqual(["foo_", "bar"]);
  });

  test("drops the breaks after the last segment", () => {
    expect(texts("foo\n")).toEqual(["foo"]);
    expect(texts("foo_\n")).toEqual(["foo"]);
    expect(texts("foo\n\n\n")).toEqual(["foo"]);
    expect(texts("foo \n ")).toEqual(["foo"]);
  });

  test("reads whitespace at the end of a segment as a word break", () => {
    expect(texts("foo /bar")).toEqual(["foo_", "bar"]);
    expect(texts("foo \nbar")).toEqual(["foo\n", "bar"]);
    expect(texts("foo \n\nbar")).toEqual(["foo\n\n", "bar"]);
    expect(texts("foo bar")).toEqual(["foo bar"]);
    expect(texts("foo /bar", false)).toEqual(["foo ", "bar"]);
  });

  test("counts a spacer on the line below it", () => {
    expect(parseLyrics("/\nfoo\nbar", true)).toEqual([
      { text: "foo\n", spacersBefore: 1 },
      { text: "bar" },
    ]);
    expect(parseLyrics("foo\n/\n/\nbar", true)).toEqual([
      { text: "foo\n" },
      { text: "bar", spacersBefore: 2 },
    ]);
  });

  test("counts a spacer at the bottom of a page on the page's last line", () => {
    expect(parseLyrics("foo\nbar\n/", true)).toEqual([
      { text: "foo\n" },
      { text: "bar", spacersAfter: 1 },
    ]);
    expect(parseLyrics("foo\n/\n\n/\nbar", true)).toEqual([
      { text: "foo\n\n", spacersAfter: 1 },
      { text: "bar", spacersBefore: 1 },
    ]);
  });

  test("counts spacers on a line's first segment", () => {
    expect(parseLyrics("fo/o\n/\nb_ar\n/\n\nbaz", true)).toEqual([
      { text: "fo/" },
      { text: "o\n" },
      { text: "b_", spacersBefore: 1, spacersAfter: 1 },
      { text: "ar\n\n" },
      { text: "baz" },
    ]);
  });

  test("ignores spacers on a page with no line", () => {
    expect(parseLyrics("foo\n\n/\n/\n\nbar", true)).toEqual([{ text: "foo\n\n" }, { text: "bar" }]);
    expect(parseLyrics("/\n\nfoo\n\n/", true)).toEqual([{ text: "foo" }]);
  });

  test("reads a line of slashes and whitespace as one spacer", () => {
    for (const spacer of [" / ", "//", "/ /"]) {
      expect(parseLyrics(`foo\n${spacer}\nbar`, true)).toEqual([
        { text: "foo\n" },
        { text: "bar", spacersBefore: 1 },
      ]);
    }
  });

  test("doesn't read a split at the edge of a line as a spacer", () => {
    expect(parseLyrics("foo/\n/bar", true)).toEqual([{ text: "foo\n" }, { text: "bar" }]);
  });

  test("reads back the lyrics joinLyrics writes", () => {
    for (const lyrics of ["/\nfoo_bar\n/\nba/z\n/\n\n/\n/\nqux\n/", "fo/o\n\nbar", "foo\n/\n/"]) {
      const segments = parseLyrics(lyrics, true);
      expect(joinLyrics(segments)).toBe(lyrics);
      expect(parseLyrics(joinLyrics(segments), true)).toEqual(segments);
    }
  });

  test("counts spacers without markup", () => {
    expect(parseLyrics("foo\n/\nbar", false)).toEqual([
      { text: "foo\n" },
      { text: "bar", spacersBefore: 1 },
    ]);
  });

  test("applies the same rules without markup", () => {
    expect(texts("foo_\nbar", false)).toEqual(["foo\n", "bar"]);
    expect(texts("a__b", false)).toEqual(["a ", "b"]);
    expect(texts("al//chemy", false)).toEqual(["al", "chemy"]);
  });

  test("doesn't draw the markup of a break before a line break", () => {
    const events: LyricEvent[] = [
      [1, LYRIC_MARKERS.SEGMENT_START],
      [2, LYRIC_MARKERS.SEGMENT_START],
    ];
    const [screen] = compileLyricTimings(fromEvents("foo_\nbar", events));
    expect(screen.lines.map((line) => line.segments.map(({ text }) => text.trim()))).toEqual([
      ["foo"],
      ["bar"],
    ]);
  });
});

